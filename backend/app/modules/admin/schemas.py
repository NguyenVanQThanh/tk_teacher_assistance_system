import re
from datetime import date, datetime
from typing import List, Optional
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict, field_validator


class AdminUserListItem(BaseModel):
    """
    Schema for a user item in the administrative list view.
    """
    model_config = ConfigDict(from_attributes=True)

    id: UUID
    user_id: UUID
    full_name: str
    phone: Optional[str] = None
    email: Optional[str] = None
    birthday: Optional[date] = None
    role: str
    role_key: str
    status: str
    department: Optional[str] = None
    class_name: Optional[str] = None
    code: Optional[str] = None
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None
    last_login_relative: Optional[str] = "Never logged in"


class AdminUserListResponse(BaseModel):
    """
    Paginated user list response.
    """
    items: List[AdminUserListItem]
    total: int
    page: int
    page_size: int
    total_pages: int


class AdminUserCreateRequest(BaseModel):
    """
    Schema for creating a new user with comprehensive validation.
    """
    full_name: str = Field(..., min_length=2, max_length=100, description="Full name of the user")
    role: str = Field(..., description="Role of the user: Student, Teacher, or Admin")
    phone: Optional[str] = Field(None, description="Vietnamese 10-digit phone number starting with 0")
    email: Optional[str] = Field(None, description="Valid email address")
    birthday: Optional[date] = Field(None, description="Birth date (YYYY-MM-DD)")
    code: Optional[str] = Field(None, max_length=50, description="Identifier code (e.g. HS2024108, GV2024042)")
    department: Optional[str] = Field(None, max_length=100, description="Department for teachers or homeroom")
    class_name: Optional[str] = Field(None, max_length=100, description="Class name for students")
    class_id: Optional[str] = Field(None, description="Class UUID if assigning directly to existing class")
    status: Optional[str] = Field("ACTIVE", description="Initial account status (ACTIVE, INACTIVE, SUSPENDED)")
    password: Optional[str] = Field(None, description="Optional custom password; if empty, system auto-generates default password")
    is_active_immediately: Optional[bool] = Field(True, description="Whether to activate immediately")

    @field_validator("full_name")
    @classmethod
    def validate_full_name(cls, v: str) -> str:
        trimmed = v.strip()
        if len(trimmed) < 2:
            raise ValueError("Full name must be at least 2 characters long.")
        name_regex = re.compile(
            r"^[a-zA-Z\sàáảãạăắằẳẵặâấầẩẫậđèéẻẽẹêếềểễệìíỉĩịòóỏõọôốồổỗộơớờởỡợùúủũụưứừửữựỳýỷỹỵÀÁẢÃẠĂẮẰẲẴẶÂẤẦẨẪẬĐÈÉẺẼẸÊẾỀỂỄỆÌÍỈĨỊÒÓỎÕỌÔỐỒỔỖỘƠỚỜỞỠỢÙÚỦŨỤƯỨỪỬỮỰỲÝỶỸỴ]+$"
        )
        if not name_regex.match(trimmed):
            raise ValueError("Full name cannot contain numbers or special characters.")
        return trimmed

    @field_validator("phone")
    @classmethod
    def validate_phone(cls, v: Optional[str]) -> Optional[str]:
        if not v:
            return None
        cleaned = re.sub(r"[\s\-\.]", "", v.strip())
        if not cleaned:
            return None
        if not re.match(r"^0\d{9}$", cleaned):
            raise ValueError("Phone number must contain exactly 10 digits starting with 0 (e.g. 0912345678) and no letters or special characters.")
        return cleaned

    @field_validator("email")
    @classmethod
    def validate_email(cls, v: Optional[str]) -> Optional[str]:
        if not v:
            return None
        cleaned = v.strip().lower()
        if not cleaned:
            return None
        if not re.match(r"^[\w\.-]+@([\w-]+\.)+[\w-]{2,4}$", cleaned):
            raise ValueError("Invalid email format.")
        return cleaned

    @field_validator("role")
    @classmethod
    def validate_role(cls, v: str) -> str:
        normalized = v.strip().capitalize()
        valid_roles = {"Admin", "Teacher", "Student"}
        if normalized not in valid_roles:
            raise ValueError(f"Role must be one of: {', '.join(valid_roles)}")
        return normalized


class AdminUserCreateResponse(BaseModel):
    """
    Response schema after creating a new user, returning auto-generated password and notification confirmation.
    """
    id: UUID
    user_id: UUID
    full_name: str
    role: str
    phone: Optional[str] = None
    email: Optional[str] = None
    status: str
    code: Optional[str] = None
    department: Optional[str] = None
    class_name: Optional[str] = None
    temporary_password: str = Field(..., description="Default password auto-generated by the system")
    notification_sent: bool = Field(True, description="Indicates whether notification was dispatched to the user")
    notification_channel: str = Field("SMS / System Notification", description="Channel used for sending credentials")
    notification_message: str = Field(..., description="Details regarding dispatch status")
    created_at: Optional[datetime] = None


